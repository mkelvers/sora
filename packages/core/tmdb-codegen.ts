import { writeFile } from "node:fs/promises";

import { z } from "zod";

/**
 * Generates TMDB's request types (paths, path parameters, query parameters)
 * from its published OpenAPI spec.
 *
 * Only GET operations are read, and response bodies are ignored: the spec
 * derives them from sample payloads, so every field is marked present and
 * non-null. Responses are validated by the Zod schemas in
 * `src/tmdb/resources.ts` instead.
 *
 * Run with `bun run tmdb:generate`.
 */
const ParameterSchema = z.object({
	in: z.enum(["path", "query", "header", "cookie"]),
	name: z.string(),
	required: z.boolean().optional(),
	schema: z
		.object({
			type: z.string().optional(),
		})
		.optional(),
});

type Parameter = z.infer<typeof ParameterSchema>;

const PathsSchema = z.record(
	z.string(),
	z.object({
		get: z
			.object({
				parameters: z.array(ParameterSchema).optional(),
			})
			.optional(),
	}),
);

/** The paths of TMDB's OpenAPI spec, as far as their GET operations' parameters go. */
class Spec {
	readonly #paths: z.infer<typeof PathsSchema>;

	constructor(paths: z.infer<typeof PathsSchema>) {
		this.#paths = paths;
	}

	/** One `TmdbEndpoints` member for each GET operation. */
	get endpoints(): string[] {
		return Object.entries(this.#paths)
			.filter(([, item]) => item.get)
			.map(([path, item]) => {
				const parameters = item.get?.parameters ?? [];
				const pathBlock = Spec.#block(parameters, "path");
				const queryBlock = Spec.#block(parameters, "query");

				return `${JSON.stringify(path.replace(/^\/3/u, ""))}: { path: ${pathBlock}; query: ${queryBlock} };`;
			});
	}

	static #block(parameters: Parameter[], location: Parameter["in"]) {
		const members = parameters
			.values()
			.filter((parameter) => parameter.in === location)
			.map((parameter) => {
				let optional = "?";

				if (parameter.required) {
					optional = "";
				}

				return `${JSON.stringify(parameter.name)}${optional}: ${Spec.#type(parameter)};`;
			})
			.toArray();

		if (members.length === 0) {
			return "{}";
		}

		return `{\n${members.join("\n")}\n}`;
	}

	static #type(parameter: Parameter) {
		switch (parameter.schema?.type) {
			case "integer":
			case "number": {
				return "number";
			}

			case "boolean": {
				return "boolean";
			}

			default: {
				return "string";
			}
		}
	}
}

const response = await fetch("https://developer.themoviedb.org/openapi/tmdb-api.json");

if (!response.ok) {
	throw new Error(`TMDB spec returned ${response.status}`);
}

const { paths } = z
	.object({
		paths: PathsSchema,
	})
	.parse(await response.json());

const { endpoints } = new Spec(paths);

await writeFile(
	"src/tmdb/api.generated.ts",
	`/* Generated by tmdb-codegen.ts. Do not edit. */

/** The path and query parameters of every TMDB v3 GET endpoint, by path template. */
export interface TmdbEndpoints {\n${endpoints.join("\n")}\n}
`,
);
